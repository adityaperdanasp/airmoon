// Deterministic pick per (day, prayerIndex) so the message rotates day to
// day and differs across the 5 prayers of the same day, without needing
// any stored state — same "day-of-year mod length" idea as
// data/headlines.js's todaysHeadlineIndex(), extended with the prayer's
// own position so Subuh and Isya on the same day don't match.
export function pickPrayerMessage(dateKey, prayerIndex, label) {
  const dayNum = Number(dateKey.replaceAll('-', ''));
  const index = (dayNum * 5 + prayerIndex) % PRAYER_MESSAGES.length;
  return PRAYER_MESSAGES[index].replaceAll('%s', label);
}
